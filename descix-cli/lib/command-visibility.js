/**
 * Command Visibility — the PUBLIC-vs-admin CLI help listing.
 *
 * CEO ruling (verbatim): "The microservice manifest consumed by DeSciX core should determine
 * what gets exposed via MCP (and therefore CLI listing should be easily exposed there too for
 * the core itself) - shouldn't we reuse that surface." And: "It's not a worry that admin
 * commands can be discovered by normal users but rather we are trying to avoid the flood of
 * noise so it is acceptable to have two lists that can be derived from the same manifest."
 *
 * THE CLASS COMES FROM THE SERVER AT RUNTIME (`get_command_surface`, guest-allowed) — there is
 * NO committed class table in this repo. The only thing committed here is
 * lib/verb-invokes.generated.json, a CLI-owned fact ("this verb invokes these commands"),
 * regenerated by scripts/generate-verb-invokes.mjs from bin/descix.js + lib/** itself.
 *
 * A verb is hidden from the default listing when it invokes at least one command AND every
 * command it invokes is classified 'admin' by the server. A verb with no recorded invokes
 * (local-only, or a verb whose only invoke call sites are dynamic — see
 * scripts/lib/verb-invoke-graph.mjs) stays visible: absence of information is not evidence of
 * admin-only-ness. A GROUP (a command with children and no action of its own) is hidden when
 * every one of its children ends up hidden — hiding is transitive up the tree, computed
 * bottom-up from the LIVE commander tree (never a second, hand-kept tree).
 *
 * Hiding is LISTING ONLY. A hidden verb still EXECUTES normally when typed; the server's own
 * permission gate (checkCommandPermission) is the actual enforcement, unchanged by this file.
 */
import fs from 'fs/promises';
import path from 'path';
import os from 'os';
import VERB_INVOKES from './verb-invokes.generated.json' with { type: 'json' };

const CACHE_PATH = path.join(os.homedir(), '.descix', 'command-surface-cache.json');
/** Short TTL: this is a LISTING convenience cache, not a security boundary — a stale read only
 * ever risks showing (or hiding) a help row for a few minutes, never changes what executes. */
const CACHE_TTL_MS = 5 * 60 * 1000;

/**
 * ONE explicit, CLI-owned declaration: Drive content authoring (`descix drive pull/push`) needs
 * infrastructure admin credentials (Google ADC / a Drive service account) that `get_command_surface`
 * has no visibility into — it is not gated by any COMMAND_PERMISSIONS entry the server classifies
 * 'admin', so it can never be derived from the manifest. Per the CEO's ruling these stay OUT of
 * the public CLI listing (internal Drive authoring still uses them — hidden, never deleted). The
 * `drive` group itself is included for clarity; it would also be hidden automatically once both
 * of its children are (see applyVisibility's group rule), but naming it here keeps this ONE set
 * the single place that answers "why is drive hidden" rather than splitting the answer across a
 * declaration and an inference.
 */
export const INFRA_ADMIN_HIDDEN_PATHS = new Set(['drive', 'drive pull', 'drive push']);

/** @returns {Record<string,string[]>} the committed, generated verb -> invoked-commands map. */
export function getVerbInvokeMap() {
  return VERB_INVOKES;
}

/**
 * Fetch the server's per-command visibility surface as a guest (no login needed).
 * @param {import('./api-client.js').DeSciXApiClient} apiClient
 * @returns {Promise<{ service: string, manifest_hash: string, commands: Record<string,'public'|'admin'> }>}
 */
export async function fetchCommandSurface(apiClient) {
  const resp = await apiClient.invoke('get_command_surface', {}, { allowGuest: true });
  const msg = resp?.message || resp;
  if (!msg || typeof msg.commands !== 'object' || msg.commands === null) {
    throw new Error(`get_command_surface returned an unexpected shape: ${JSON.stringify(resp)}`);
  }
  return msg;
}

async function readCache() {
  try {
    const raw = await fs.readFile(CACHE_PATH, 'utf8');
    return JSON.parse(raw);
  } catch {
    return {};
  }
}

async function writeCache(cache) {
  try {
    await fs.mkdir(path.dirname(CACHE_PATH), { recursive: true });
    await fs.writeFile(CACHE_PATH, JSON.stringify(cache, null, 2), 'utf8');
  } catch {
    // Best-effort. A cache write failure must never break help output — the caller already has
    // the freshly-fetched surface in hand and can render with it regardless.
  }
}

/**
 * The server surface for `origin`, from the user-level cache (keyed by origin, short TTL) when
 * fresh, else fetched live and cached. Throws if the fetch fails (network down, old server
 * without the command, etc.) — the caller decides what "help shows everything" means.
 *
 * @param {string} origin
 * @param {import('./api-client.js').DeSciXApiClient} apiClient
 * @returns {Promise<{ commands: Record<string,'public'|'admin'>, fromCache: boolean }>}
 */
export async function getCommandSurface(origin, apiClient) {
  const cache = await readCache();
  const entry = cache[origin];
  if (entry && typeof entry.fetchedAt === 'number' && (Date.now() - entry.fetchedAt) < CACHE_TTL_MS) {
    return { commands: entry.surface.commands, fromCache: true };
  }
  const surface = await fetchCommandSurface(apiClient);
  cache[origin] = { surface, fetchedAt: Date.now() };
  await writeCache(cache);
  return { commands: surface.commands, fromCache: false };
}

/**
 * Should a single LEAF verb (identified by its full space-joined path, e.g. "kb corpus sync") be
 * hidden from the default listing, given the server's command->visibility surface?
 *
 * @param {string} verbPath
 * @param {Record<string,'public'|'admin'>} surfaceCommands
 * @returns {boolean}
 */
export function shouldHideLeaf(verbPath, surfaceCommands) {
  if (INFRA_ADMIN_HIDDEN_PATHS.has(verbPath)) return true;
  const invokes = VERB_INVOKES[verbPath];
  if (!invokes || invokes.length === 0) return false; // no recorded invokes -> stays visible
  return invokes.every((cmd) => surfaceCommands[cmd] === 'admin');
}

/**
 * Apply hide/show to the LIVE commander tree rooted at `program`, bottom-up. Never reads or
 * builds a second command tree — `cmd.commands` / `cmd._actionHandler` (commander's own runtime
 * state) is the only source of "what verbs exist and how they nest", so this can never drift
 * from the tree `--help` actually renders.
 *
 * @param {import('commander').Command} program
 * @param {Record<string,'public'|'admin'>} surfaceCommands
 */
export function applyVisibility(program, surfaceCommands) {
  function visit(cmd, pathTokens) {
    const verbPath = pathTokens.join(' ');
    const hasChildren = Array.isArray(cmd.commands) && cmd.commands.length > 0;
    // ADDITIVE ONLY. Some commands are registered `{ hidden: true }` by the CLI itself for
    // reasons that have nothing to do with server admin-gating — see the retired-surface
    // registrations in lib/commands/retired-kb-sync.js, each a deliberate loud-refusal stub kept
    // out of the default listing so it doesn't clutter it, while still working and refusing
    // clearly when typed. This layer may HIDE a visible command; it must never REVEAL a command
    // the CLI already chose to hide. MEASURED: an early version unconditionally overwrote
    // `_hidden`, which un-hid a retired-surface stub the moment its verb had no generated-map
    // entry (it invokes no /apifront command at all, so its invoke list is empty).
    const alreadyHidden = !!cmd._hidden;

    if (hasChildren) {
      let allChildrenHidden = true;
      for (const child of cmd.commands) {
        const childHidden = visit(child, [...pathTokens, child.name()]);
        if (!childHidden) allChildrenHidden = false;
      }
      if (pathTokens.length === 0) return false; // never hide the root program
      if (cmd._actionHandler) {
        // A command that is BOTH a group and its own runnable leaf (not used in this CLI today,
        // but commander allows it) is judged as a leaf: its own invokes decide it, independent
        // of its children.
        const hidden = alreadyHidden || shouldHideLeaf(verbPath, surfaceCommands);
        cmd._hidden = hidden;
        return hidden;
      }
      cmd._hidden = alreadyHidden || allChildrenHidden;
      return cmd._hidden;
    }

    if (pathTokens.length === 0) return false; // the root has no children in practice, but guard anyway
    const hidden = alreadyHidden || shouldHideLeaf(verbPath, surfaceCommands);
    cmd._hidden = hidden;
    return hidden;
  }
  visit(program, []);
}

/**
 * Is this invocation one that will render `--help` output? Only these fetch the network — every
 * other invocation must stay fast and offline-safe.
 *
 * Recognizes: `-h` / `--help` anywhere, `help` in subcommand position, a bare invocation (no positional tokens once
 * global flags are stripped), and a "bare group" invocation (the resolved command has children
 * but no action handler of its own — e.g. `descix app` with no subcommand, which commander
 * renders as help even though the CLI never called outputHelp() itself).
 *
 * @param {import('commander').Command} program
 * @param {string[]} argv - process.argv.slice(2)
 * @param {{ valueFlags?: string[], booleanFlags?: string[] }} [globalFlags]
 * @returns {boolean}
 */
export function isHelpInvocation(program, argv, globalFlags = {}) {
  if (argv.length === 0) return true;
  if (argv.includes('-h') || argv.includes('--help')) return true;
  if (argv.includes('-V') || argv.includes('--version')) return false; // prints a version, renders no listing

  const valueFlags = new Set(globalFlags.valueFlags || []);
  const booleanFlags = new Set(globalFlags.booleanFlags || []);
  const positional = [];
  for (let i = 0; i < argv.length; i++) {
    const tok = argv[i];
    if (valueFlags.has(tok)) { i++; continue; }
    if (booleanFlags.has(tok)) continue;
    if (tok.startsWith('-')) continue; // an option belonging to whatever command it turns out to be
    positional.push(tok);
  }
  if (positional.length === 0) return true;

  let cmd = program;
  for (const tok of positional) {
    if (cmd._actionHandler) break; // reached a leaf; remaining tokens are ITS args, not subcommands
    if (tok === 'help') return true; // commander's help subcommand, only in subcommand position
    const next = (cmd.commands || []).find((c) => c.name() === tok || (c.aliases && c.aliases().includes(tok)));
    if (!next) return false; // unresolvable path — commander's own error path, not ours to fetch for
    cmd = next;
  }
  return !cmd._actionHandler;
}
